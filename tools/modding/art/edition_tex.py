"""Build the 4-bit 'JAKE EDITION' texture (Knewave set upright, logo style)
and write edition.inc for the play-as-jake plugin."""
import sys
from PIL import Image
import edition as E

FONT = "fonts/Knewave-Regular.ttf"
SHEAR = -0.28
TEX_W = 256

orig_mask = E.letter_mask
def upright(ch, font, angle):
    m = orig_mask(ch, font, 0)
    w = m.width + int(-SHEAR * m.height)
    m = m.transform((w, m.height), Image.AFFINE, (1, SHEAR, -SHEAR * m.height, 0, 1, 0),
                    resample=Image.BICUBIC)
    m = m.rotate(angle, resample=Image.BICUBIC, expand=True)
    return m.crop(m.getbbox())
E.letter_mask = upright

def build():
    font = E.ImageFont.truetype(FONT, 44 * E.SS)
    face = E.layout("JAKE EDITION", font, (-8, 6, -4, 9, 0, -6, 7, -3, 5, -7, 4, -5),
                    [b * E.SS for b in (0, -4, 3, -2, 0, 4, -3, 2, -4, 3, -2, 1)],
                    gap=-2 * E.SS, space=12 * E.SS)
    im = E.style(face, outline=2 * E.SS, depth=7 * E.SS, rim=E.SS)
    w = TEX_W - 2
    h = round(im.height * w / im.width)
    im = im.resize((w, h), Image.LANCZOS)
    # 15 colours + transparent (index 0)
    alpha = im.getchannel("A").point(lambda a: 255 if a >= 110 else 0)
    rgb = Image.new("RGB", im.size, (0, 0, 0)); rgb.paste(im.convert("RGB"), (0, 0), alpha)
    q = rgb.quantize(colors=15, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = q.getpalette()[:45]
    idx = [[0] * TEX_W for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if alpha.getpixel((x, y)):
                idx[y][x + 1] = q.getpixel((x, y)) + 1
    return idx, [tuple(pal[3 * i:3 * i + 3]) for i in range(15)], h

def to555(c):
    r, g, b = (max(1, v >> 3) for v in c)
    return r | g << 5 | b << 10

if __name__ == "__main__":
    idx, pal, h = build()
    colours = [0] + [to555(c) for c in pal]
    prev = Image.new("RGB", (TEX_W, h), (40, 120, 40))
    for y in range(h):
        for x in range(TEX_W):
            if idx[y][x]: prev.putpixel((x, y), pal[idx[y][x] - 1])
    prev.save(sys.argv[1] if len(sys.argv) > 1 else "edition_preview.png")
    halves = []
    for y in range(h):
        for x in range(0, TEX_W, 4):
            halves.append(idx[y][x] | idx[y][x + 1] << 4 | idx[y][x + 2] << 8 | idx[y][x + 3] << 12)
    with open("edition.inc", "w") as f:
        f.write("/* Generated by modding/art/edition_tex.py - 'JAKE EDITION', 4-bit, %dx%d. */\n" % (TEX_W, h))
        f.write("enum { JAKE_EDITION_W = %d, JAKE_EDITION_H = %d };\n" % (TEX_W, h))
        f.write("static const uint16_t JAKE_EDITION_PALETTE[16] = {\n")
        f.write(",\n".join("    " + ", ".join("0x%04X" % c for c in colours[i:i + 8]) for i in range(0, 16, 8)) + "\n};\n")
        f.write("static const uint16_t JAKE_EDITION_TEXELS[%d] = {\n" % len(halves))
        for i in range(0, len(halves), 16):
            f.write("    " + ", ".join("0x%04X" % v for v in halves[i:i + 16]) + ",\n")
        f.write("};\n")
    print("texture", TEX_W, "x", h)
