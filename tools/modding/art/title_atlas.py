"""Title-screen atlas for the play-as-jake plugin (all our own art):
'JAKE EDITION', the NORMAL / EVIL labels and an 'L1' hint in the logo style
(one shared 15-colour palette), and the two 36x32 portraits (their own
palettes). 256 wide, 4-bit; writes title_atlas.inc."""
import sys
from PIL import Image, ImageFont, ImageDraw
import edition as E
import edition_tex as T
import portrait as P

W, H = 256, 110
LABEL_FONT = "fonts/LuckiestGuy-Regular.ttf"     # rounder: Knewave's V reads as I this small
def logo_text(text, size, depth, bounce=(0, -2, 2, -1, 1, -2), tilt=(-6, 5, -3, 7, -4, 4)):
    font = ImageFont.truetype(LABEL_FONT, size * E.SS)
    face = E.layout(text, font, tilt, [b * E.SS for b in bounce], gap=1 * E.SS, space=10 * E.SS)
    return E.style(face, outline=3 * E.SS, depth=depth * E.SS, rim=E.SS)
def fit(im, w, h):
    s = min(w / im.width, h / im.height)
    return im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
def hint(text):
    f = ImageFont.truetype("C:/Windows/Fonts/ariblk.ttf", 13 * E.SS)
    l, t, r, b = f.getbbox(text)
    im = Image.new("RGBA", (r - l + 8 * E.SS, b - t + 8 * E.SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.text((4 * E.SS - l, 4 * E.SS - t), text, font=f, fill=(255, 250, 225, 255),
           stroke_width=2 * E.SS, stroke_fill=(10, 20, 90, 255))
    return im.crop(im.getbbox())

# name: (image, x, y)
texts = {}
ed = T.build_rgba()
texts["edition"] = (ed, 1, 0)
texts["normal"] = (fit(logo_text("NORMAL", 40, 5), 170, 24), 80, 62)
texts["evil"] = (fit(logo_text("EVIL", 40, 5), 120, 24), 80, 86)
texts["hint"] = (fit(hint("L1"), 48, 20), 200, 89)

canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
rects = {}
for name, (im, x, y) in texts.items():
    canvas.paste(im, (x, y), im); rects[name] = (x, y, im.width, im.height)
alpha = canvas.getchannel("A").point(lambda a: 255 if a >= 110 else 0)
rgb = Image.new("RGB", (W, H)); rgb.paste(canvas.convert("RGB"), (0, 0), alpha)
q = rgb.quantize(colors=15, method=Image.MEDIANCUT, dither=Image.NONE)
qp = q.getpalette()[:45]
idx = [[(q.getpixel((x, y)) + 1) if alpha.getpixel((x, y)) else 0 for x in range(W)] for y in range(H)]
text_pal = [0] + [T.to555(tuple(qp[3 * i:3 * i + 3])) for i in range(15)]

# portraits: own indices/palettes, at (0,64) and (40,64)
ports = {}
for n, kind in enumerate(("normal", "evil")):
    px, pal = P.build(kind)
    x0, y0 = 40 * n, 64
    for y in range(P.H):
        for x in range(P.W):
            idx[y0 + y][x0 + x] = px[y][x]
    ports[kind] = (x0, y0, pal)
    rects["face_" + kind] = (x0, y0, P.W, P.H)
# the portraits' rectangle must not overlap any text
for name in ("normal", "evil", "hint"):
    x, y, w, h = rects[name]; assert x >= 76, name

halves = [idx[y][x] | idx[y][x + 1] << 4 | idx[y][x + 2] << 8 | idx[y][x + 3] << 12
          for y in range(H) for x in range(0, W, 4)]
with open("title_atlas.inc", "w") as f:
    f.write("/* Generated by modding/art/title_atlas.py: 'JAKE EDITION', NORMAL/EVIL, L1 hint,\n"
            " * and the two portraits - our own art, 4-bit %dx%d. */\n" % (W, H))
    f.write("enum { TITLE_ATLAS_W = %d, TITLE_ATLAS_H = %d };\n" % (W, H))
    f.write("enum { TITLE_TEXT_PALETTE, TITLE_NORMAL_PALETTE, TITLE_EVIL_PALETTE, TITLE_PALETTES };\n")
    f.write("static const uint16_t TITLE_ATLAS_PALETTES[TITLE_PALETTES][16] = {\n")
    for pal in (text_pal, ports["normal"][2], ports["evil"][2]):
        f.write("    { " + ", ".join("0x%04X" % c for c in pal) + " },\n")
    f.write("};\n")
    f.write("typedef struct TitleRect { uint8_t u, v, w, h; } TitleRect;\n")
    for name, (x, y, w, h) in rects.items():
        f.write("static const TitleRect TITLE_%s = { %d, %d, %d, %d };\n" % (name.upper(), x, y, w, h))
    f.write("static const uint16_t TITLE_ATLAS_TEXELS[%d] = {\n" % len(halves))
    for i in range(0, len(halves), 16):
        f.write("    " + ", ".join("0x%04X" % v for v in halves[i:i + 16]) + ",\n")
    f.write("};\n")
prev = Image.new("RGB", (W, H), (40, 120, 40))
for y in range(H):
    for x in range(W):
        k = idx[y][x]
        if not k: continue
        if x < 76 and y >= 64: pal = ports["normal" if x < 40 else "evil"][2]
        else: pal = text_pal
        c = pal[k]; prev.putpixel((x, y), ((c & 31) << 3, ((c >> 5) & 31) << 3, ((c >> 10) & 31) << 3))
prev.resize((W * 3, H * 3), Image.NEAREST).save(sys.argv[1])
print(rects)
